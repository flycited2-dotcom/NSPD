def enquiry(data, candidate_id):
    land_status.enquiry(data, candidate_id)  # Same immutable candidate/version contract.
    result = data['result']
    candidate = next(c for c in result['candidates'] if c['id'] == candidate_id)
    sources = result.get('sources', {})
    purpose = {'housing': 'ИЖС', 'personal_farm': 'ЛПХ', 'agriculture': 'сельскохозяйственное использование'}.get(
        result.get('parameters', {}).get('purpose'), 'цель не выбрана; уточнить перед отправкой')
    lines = ['ПРОЕКТ ЗАПРОСА О ЗОНЕ И ДЕЙСТВУЮЩИХ ПЗЗ — НЕ ОТПРАВЛЕН',
             'Адресат: [уточнить компетентный орган, подразделение и официальный канал]',
             'Заявитель и обратный адрес: [заполнить перед отправкой]', '',
             'Прошу предоставить доступные сведения о градостроительном регулировании территории '
             'в соответствии с приложенным поисковым контуром GeoJSON.',
             f"Контур: {candidate['id']}. Версия расчёта: {result['id']} от {result.get('created_at')}.",
             f"Расчётная площадь: {candidate['area_m2']} м². Точка внутри (долгота, широта): {candidate['point']}.",
             f"Кадастровый номер контура: {candidate.get('cadastral_number') or 'не установлен; номер не присваивался'}.",
             'Координаты приложения — WGS84, долгота/широта в градусах. Границы и площадь поисковые; '
             'надлежащая система координат для дальнейших работ требует уточнения.',
             f'Предполагаемая цель исследования: {purpose}. Это не подтверждённый ВРИ.', '',
             *[f'{i}. {question}' for i, question in enumerate(QUESTIONS, 1)], '',
             'Приложение: GeoJSON с точными вершинами этого контура и той же версией расчёта.',
             'Контекст локального исследования (не доказательство действия норм):',
             f"Каталог документов ПЗЗ: {sources.get('planning', {}).get('id') or 'не подключён'}.",
             f"Индекс полного текста: {sources.get('regulations', {}).get('id') or 'не подключён'}.",
             f"Индекс карт: {result.get('source_inputs', {}).get('planning_maps') or 'не подключён'}.",
             'Полученные соседние участки, названия зон в текстах и растровые фрагменты '
             'не использованы как подтверждение зоны этого контура.',
             'Это запрос информации, не заявление о предоставлении земли, ГПЗУ, регистрации права или участии в торгах.',
             WARNING]
    if data.get('stale'):
        lines.append('ВНИМАНИЕ: версия расчёта устарела; перед отправкой обновите источники и приложение.')
    lines.extend(['', 'Геометрия WGS84:', json.dumps(candidate['geometry'], ensure_ascii=False)])
    return ('\n'.join(lines) + '\n').encode('utf-8')


def geometry(data, candidate_id):
    result = land_status.enquiry_geometry(data, candidate_id)
    result.update(purpose='Приложение к неотправленному запросу о ПЗЗ', warning=WARNING,
                  territorial_zone_confirmed=False, regulation_current_confirmed=False)
    return result


def dossier_section(result, candidate, stale=False):
    query = '?' + html.escape(urlencode({'result_id': result.get('id', ''), 'id': candidate['id']}), quote=True)
    return ('<h3>Получение сведений о действующей зоне ПЗЗ</h3>'
            '<p>Зона этого контура и применимая редакция регламентов требуют подтверждения по официальным сведениям.</p>'
            '<p><a href="/api/recon/planning-request' + query + '">Скачать проект запроса о ПЗЗ</a> · '
            '<a href="/api/recon/planning-request.geojson' + query + '">Скачать контур для запроса о ПЗЗ</a></p>'
            + ('<p>Расчёт устарел: перед отправкой обновите источники.</p>' if stale else '')
            + '<p>Проект не отправлен. Вопросы: зоны/подзоны и границы, система координат, действующие изменения, '
            'ВРИ и параметры, красные линии и планировочные документы.</p>')
